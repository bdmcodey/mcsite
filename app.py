import json
import os

from flask import Flask, render_template, send_from_directory, Response, redirect, url_for, make_response
from markupsafe import Markup

app = Flask(__name__)
 
 
@app.route('/')
def index():
    return render_template('index.html')
 
 
@app.route('/projects/')
def projects():
    return render_template('projects.html')
 
 
@app.route('/resume/')
def resume():
    return render_template('resume.html')
 
 
@app.route('/contact/')
def contact():
    return render_template('contact.html')
 
 
# Pages from the pre-2026 site. Old links and search results still point here,
# so send them to the homepage permanently instead of a 404.
@app.route('/home/', strict_slashes=False)
@app.route('/about/', strict_slashes=False)
def old_pages():
    return redirect(url_for('index'), code=301)
 
 
# Unlisted: not linked from anywhere on the site. Served as a raw static file
# (not render_template) so Jinja never tries to parse the dashboard's JS braces.
# Kept out of search via a response header rather than robots.txt, which would
# advertise the URL.
@app.route('/lastfm')
def lastfm():
    resp = send_from_directory(app.static_folder, 'lastfm.html')
    resp.headers['X-Robots-Tag'] = 'noindex, nofollow'
    return resp
 
 
# Companion page for the ALA Core Forum poster; the poster's QR code points here.
# Unlisted while it is a draft: not in the nav or the sitemap, and kept out of
# search by header, as /lastfm is. The figures are generated by
# poster/build_figures.py and inlined, so the page's CSS can theme them.
POSTER_FIGURES = ('statement', 'tokens', 'releases-wide', 'releases-tall', 'silent-loss', 'qr', 'usc-logo')


def _poster_page(template):
    fig_dir = os.path.join(app.static_folder, 'poster', 'figures')
    figures = {}
    for name in POSTER_FIGURES:
        with open(os.path.join(fig_dir, f'{name}.svg'), encoding='utf-8') as f:
            figures[name.replace('-', '_')] = Markup(f.read())
    with open(os.path.join(app.root_path, 'poster', 'numbers.json'), encoding='utf-8') as f:
        numbers = json.load(f)
    resp = make_response(render_template(template, fig=figures, n=numbers))
    resp.headers['X-Robots-Tag'] = 'noindex, nofollow'
    return resp


@app.route('/poster/')
def poster():
    return _poster_page('poster.html')


# The printed poster itself, 36 x 48 in. plus bleed, as a page. poster/build_poster.py
# turns it into the PDF sent to the printer.
@app.route('/poster/print/')
def poster_print():
    return _poster_page('poster_print.html')


@app.route('/robots.txt')
def robots():
    return Response(
        "User-agent: *\nAllow: /\nSitemap: https://matthewcodey.com/sitemap.xml\n",
        mimetype="text/plain",
    )
 
 
@app.route('/sitemap.xml')
def sitemap():
    pages = ['/', '/projects/', '/resume/', '/contact/']  # /lastfm deliberately omitted
    urls = "".join(f"<url><loc>https://matthewcodey.com{p}</loc></url>" for p in pages)
    xml = ('<?xml version="1.0" encoding="UTF-8"?>'
           '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">'
           f'{urls}</urlset>')
    return Response(xml, mimetype="application/xml")
 
 
@app.errorhandler(404)
def not_found(e):
    return render_template('404.html'), 404
 
 
if __name__ == '__main__':
    app.run(debug=True)